/*!
 * @file aot_entry.c
 * @brief
 *  AOT program entry: the main() of every compiled LuaC program.
 *
 *  Unlike v1's RuntimeMain (runtime_init.c), there is NO embedded bytecode
 *  blob, NO embedded packages, NO native-DLL bootstrap and NO blob crypto/
 *  decompress passes -- those symbols (g_LuaBlob, Runtime_GetPackages,
 *  EmbeddedLoader_*, InstallEmbeddedPackages, Native_Bootstrap) do not exist
 *  in an AOT program and referencing them would break the link.
 *
 *  Instead, the program's function bodies are compiled to native code ahead
 *  of time and emitted as luac_fn_<id> symbols. At startup we:
 *      1. stand up a Lua state and open the standard libraries,
 *      2. install a lookup-only dispatch hook so luaV_execute routes a Lua
 *         closure call to its pre-registered AOT body (no JIT at runtime),
 *      3. call the generated LuacProgram_BuildEntry, which reconstructs every
 *         Proto and registers each one's luac_fn_<id> into the dispatch cache
 *         (via Jit_RegisterCompiled), returning the main-chunk Proto,
 *      4. build the entry LClosure, bind its _ENV upvalue to the globals table
 *         exactly as lua_load does for a main chunk, and
 *      5. invoke it with a normal lua_pcall -- luaV_execute's hook then
 *         dispatches to the entry body.
 *
 *  Coroutines: fiber-based lib installed below (Coro_OpenLib). VEH and the
 *  FFI are deliberately NOT initialized in AOT programs today — no FFI means
 *  no foreign threads/faulting stubs (and ~25 KB less per exe); FFI-in-exes
 *  is an M4 item alongside builtin-package bundling.
 */

