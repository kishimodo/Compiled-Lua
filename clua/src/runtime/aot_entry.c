/* Generated by the AOT codegen (Task 13): reconstructs all Protos, registers
 * their native bodies into the dispatch cache, and returns the main-chunk
 * Proto (the program entry). Unresolved at `-c` time; linked in for real by
 * the program build. */
extern Proto *LuacProgram_BuildEntry( lua_State *L );

/*!
 * @brief
 *  Lookup-only dispatch hook installed into clua_dispatch_hook.
 *
 *  luaV_execute (lvm.c:1199) calls this with the callee closure's Proto*; we
 *  return the pre-registered AOT body for that Proto (or NULL). Lookup only:
 *  AOT bodies are registered up front by LuacProgram_BuildEntry and no code
 *  generation exists at run time.
 *
 *  Signature matches clua_dispatch_t == void *(*)(lua_State *, void *).
 */
static void *AotLookupHook( lua_State *L, void *proto ) {
    ( void )L;
    return ( void * )Jit_LookupCached( ( Proto * )proto );
}

/* FFI bring-up, linked only when the program references ffi/bit (the driver
 * adds -Wl,--undefined=Clua_OpenFfi then; see ffi_anchor.c). Weak: NULL when
 * the anchor isn't in the link. */
extern void Clua_OpenFfi( lua_State *L ) __attribute__(( weak ));

/* Basename of argv[0]: drop any directory / drive prefix, keep the file name.
 * Used for the uncaught-error banner so a compiled program reports under its
 * own name, exactly as reference Lua prints "<progname>: <msg>". */
static const char *AotProgName( const char *argv0 ) {
    const char *base = argv0;
    const char *p;
    if ( argv0 == NULL || argv0[ 0 ] == '\0' ) return "clua";
    for ( p = argv0; *p != '\0'; p++ ) {
        if ( *p == '\\' || *p == '/' || *p == ':' ) base = p + 1;
    }
    return ( *base != '\0' ) ? base : "clua";
}

/* Message handler installed under the entry call: appends a stack traceback
 * to the error object while the call chain is still live, so an uncaught
 * runtime error reports exactly like the reference interpreter does -- same
 * "<name>: <message>\n<traceback>" shape (AOT-ERRBANNER-001 resolved). The
 * leading name token is the program's own basename rather than a fixed
 * string, which is correct: a standalone exe is not the compiler. */
static int AotMsgHandler( lua_State *L ) {
    const char *msg = lua_tostring( L, 1 );
    if ( msg == NULL ) {
        if ( luaL_callmeta( L, 1, "__tostring" ) &&
             lua_type( L, -1 ) == LUA_TSTRING ) {
            return 1;
        }
        msg = lua_pushfstring( L, "(error object is a %s value)",
                               luaL_typename( L, 1 ) );
    }
    luaL_traceback( L, L, msg, 1 );
    return 1;
}

